#!/usr/bin/env node
// בדיקה של ההחלפה השקטה בחיפוש. בלי רשת ובלי דפדפן.
//
// **נולד מבדיקה ידנית של בעל האתר ב-07.11.2026.** הוא הקליד
// "יוספטל 82 בת ים" ועצר: "הכל חוץ ממה שביקשתי". שלוש סיבות היו שם,
// ושתיים תוקנו כתקלות תצוגה. השלישית היא המחלקה: **האתר הציג משהו
// אחר במקום מה שהוקלד, בלי לומר זאת.**
//
// מספר 82 פשוט אינו קיים ב-OpenStreetMap, אז אין מה למצוא — אבל מי
// שמקליד כתובת ומקבל אחרת בלי הסבר חושב שהאתר שבור.
//
// הבדיקה כאן היא על `missingHouseNumber`, שהיא טהורה בכוונה. היא לא
// שואלת "מה Photon החזיר" אלא **"האם נאמר למשתמש שלא מצאנו"**.
// load.mjs רושם את וו ההחלפה שמאפשר ל-node לטעון `./data` בלי סיומת.
// בלעדיו הייבוא נופל ב-ERR_MODULE_NOT_FOUND, והבדיקה לא רצה בכלל.
import "./load.mjs";
const { missingHouseNumber } = await import("../app/lib/useNearestStation.ts");

const P = (label, housenumber) => ({ label, lat: 0, lng: 0, housenumber });

const CASES = [
  // [תיאור, שאילתה, תוצאות, הציפייה]
  ["המקרה שנתפס: 82 הוקלד, רק 92 קיים",
    "יוספטל 82 בת ים", [P("קניון בת ים · יוספטל 92", "92"), P("יוספטל")], "82"],
  ["מספר שהוקלד ונמצא — אין להודיע",
    "יוספטל 92 בת ים", [P("קניון בת ים · יוספטל 92", "92")], null],
  ["בלי מספר בכלל — אין להודיע",
    "יוספטל בת ים", [P("יוספטל")], null],
  ["אין תוצאות — יש כבר הודעה אחרת, אין להכפיל",
    "יוספטל 82 בת ים", [], null],
  ["מספר קיים בתוצאה שנייה ולא בראשונה",
    "הרצל 5 בת ים", [P("הרצל"), P("הרצל 5", "5")], null],
  ["שני מספרים בשאילתה — נבדק הראשון",
    "דרך 4 בית 7", [P("דרך 4", "4")], null],
];

const QUIET = process.argv[2] === "count";
const say = (...a) => { if (!QUIET) console.log(...a); };

let fail = 0;
for (const [label, q, places, want] of CASES) {
  const got = missingHouseNumber(q, places);
  const ok = got === want;
  if (!ok) fail++;
  say(`${ok ? "✓" : "✗"} ${label.padEnd(44)} קיבלנו ${String(got)} · צפוי ${String(want)}`);
}

// בקרה: הפונקציה חייבת להיות מסוגלת להחזיר ערך, אחרת "אפס כשלים"
// מתוך פונקציה שתמיד מחזירה null נראה כמו הצלחה.
const canFire = missingHouseNumber("רחוב 1", [P("רחוב")]) === "1";
if (!canFire) fail++;
say(`${canFire ? "✓" : "✗"} בקרה: הפונקציה מסוגלת לירות בכלל`);

if (QUIET) console.log("%d/%d", fail, CASES.length + 1);
else console.log(fail ? `\n${fail} נכשלו` : `\nכל ${CASES.length + 1} המקרים עברו`);
process.exit(fail ? 1 : 0);
