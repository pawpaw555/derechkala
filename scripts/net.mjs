#!/usr/bin/env node
// שליפה מהרשת לבדיקות החיות. מקום אחד לשלוש הבדיקות שתלויות ברשת.
//
// נולד מכשל אמיתי שדווח ב-05.11.2026: שתי שורות בבלוק נכשלו בהרצה אחת
// ועברו בכל השאר, והעמודה חזרה **ריקה לגמרי** — לא ערך שונה. זאת
// החתימה של פקודה שלא הדפיסה כלום.
//
// הסיבה שוחזרה ולא נוחשה: דחייה של fetch ב-await עליון במודול ESM
// הורגת את הסקריפט לפני כל הדפסה, ו-`2>/dev/null` בבלוק בולע את
// העקבות. נמדד גם ש-`process.on("unhandledRejection")` **אינו** תופס
// את זה — הוא הדפיס כלום. רק try/catch עובד.
//
// `sources-live.sh` בבאש כבר עשה את זה נכון: כשמארח לא עונה הוא מדפיס
// `000(≠200)` ולא ריק. כאן אותה התנהגות ל-node.
//
// שתי ההפרדות שהכלל דורש:
//   1. "אין תשובה מהרשת" אינו "הערך השתנה". שורה בבלוק חייבת לומר מה
//      מהשניים קרה, אחרת מתעלמים ממנה.
//   2. תקלה רגעית אינה שינוי. לכן ניסיון חוזר אחד לפני שמכריזים כשל.

const RETRY_WAIT_MS = 2500;

/**
 * מושך טקסט מכתובת, עם ניסיון חוזר אחד.
 *
 * אם גם הניסיון השני נכשל — מדפיס שורה שאומרת **למה**, ויוצא ב-1.
 * ההדפסה היא ל-stdout בכוונה: הבלוק מפנה את stderr ל-/dev/null, ושורה
 * שיוצאת לשם שקולה לשתיקה.
 */
export async function liveText(label, url, opts = {}) {
  let last;
  for (let attempt = 1; attempt <= 2; attempt++) {
    try {
      const res = await fetch(url, opts);
      // גם קריאת הגוף יכולה ליפול באמצע, ולכן היא בתוך אותו try.
      return await res.text();
    } catch (err) {
      last = err;
      if (attempt === 1) await new Promise((s) => setTimeout(s, RETRY_WAIT_MS));
    }
  }
  const why = last?.cause?.code ?? last?.name ?? "שגיאה";
  console.log("אין תשובה מהרשת · %s · %s", label, why);
  process.exit(1);
}
