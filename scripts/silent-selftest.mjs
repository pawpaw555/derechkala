#!/usr/bin/env node
// **החלפה שקטה**: הערך שהמשתמש ביקש לא נמצא, הוצג משהו אחר במקומו,
// והממשק לא אמר שהחלפנו. בדיקה טהורה — בלי רשת ובלי דפדפן.
//
// **נולד מבדיקה ידנית של בעל האתר ב-07.11.2026.** הוא הקליד
// "יוספטל 82 בת ים" ועצר: "הכל חוץ ממה שביקשתי". שלוש סיבות היו שם,
// ושתיים תוקנו כתקלות תצוגה. השלישית היא המחלקה.
//
// הקובץ נקרא קודם `search-selftest.mjs`, **ושמו היה צר מדי**: סריקת
// המחלקה מצאה שאותה שתיקה יושבת בשני מקומות נוספים שאינם חיפוש —
// שדה המוצא בעמוד הבית, שהכריז "מצאנו את המקום" מעל תוצאות שאינן
// מה שהוקלד, וזמן ההליכה שנפסל, שהציג מרחק בלי זמן ובלי הסבר.
// בדיקה ששמה צר נבדקת רק במקום אחד, ולכן השם הורחב למחלקה.
//
// השאלה בכל מקרה כאן היא אחת: **האם נאמר למשתמש שהוצג משהו אחר.**
// load.mjs רושם את וו ההחלפה שמאפשר ל-node לטעון `./data` בלי סיומת.
// בלעדיו הייבוא נופל ב-ERR_MODULE_NOT_FOUND, והבדיקה לא רצה בכלל.
import "./load.mjs";
const { missingHouseNumber, houseNumberNote } = await import("../app/lib/useNearestStation.ts");
const { walkEstimate, walkNote } = await import("../app/lib/data.ts");

// השדה השלישי הוא הרחוב כפי שהמקור מסר אותו, בנפרד מהתווית. הוא נוסף
// ב-10.11.2026: בלעדיו אי אפשר להבדיל בין "הבית שהוקלד" לבין בית באותו
// מספר ברחוב אחר, וזה בדיוק מה שנשבר.
const P = (label, housenumber, street) => ({ label, lat: 0, lng: 0, housenumber, street });

// ── א. מספר בית שהוקלד ולא נמצא ─────────────────────────────────
const HOUSE = [
  // [תיאור, שאילתה, תוצאות, הציפייה]
  ["המקרה שנתפס: 82 הוקלד, רק 92 קיים",
    "יוספטל 82 בת ים", [P("קניון בת ים · יוספטל 92", "92", "יוספטל"), P("יוספטל", undefined, "יוספטל")], "82"],
  ["מספר שהוקלד ונמצא — אין להודיע",
    "יוספטל 92 בת ים", [P("קניון בת ים · יוספטל 92", "92", "יוספטל")], null],
  ["בלי מספר בכלל — אין להודיע",
    "יוספטל בת ים", [P("יוספטל", undefined, "יוספטל")], null],
  ["אין תוצאות — יש כבר הודעה אחרת, אין להכפיל",
    "יוספטל 82 בת ים", [], null],
  ["מספר קיים בתוצאה שנייה ולא בראשונה",
    "הרצל 5 בת ים", [P("הרצל", undefined, "הרצל"), P("הרצל 5", "5", "הרצל")], null],
  ["שני מספרים בשאילתה — נבדק הראשון",
    "דרך 4 בית 7", [P("דרך 4", "4", "דרך")], null],
  // ── המקרה של 10.11.2026, מהמסך של בעל האתר ──────────────────
  ["המספר נמצא ברחוב אחר — חייבים להודיע",
    "הוד השרון הרמה 1",
    [P("שיבולת השרון · זקיף 1 · רמות מנחם · הוד השרון", "1", "זקיף"),
     P("הרמה · הוד השרון", undefined, "הרמה")], "1"],
  ["אותו מספר, והפעם ברחוב שהוקלד — אין להודיע",
    "הוד השרון הרמה 1", [P("הרמה 1 · הוד השרון", "1", "הרמה")], null],
  ["מקור שלא מסר רחוב — לא נספר כהתאמה, וזה מכוון",
    "סוקולוב 18 הוד השרון", [P("סוקולוב 18", "18")], "18"],
];

// ── ב. זמן הליכה שנפסל ───────────────────────────────────────────
// `walkEstimate` פוסלת מסלול עקיף ומחזירה קו אווירי **בלי זמן**. עד
// 07.11.2026 שני מקומות הציגו את המרחק הזה בשתיקה מלאה.
const WALK = [
  // [תיאור, אווירי, מסלול, האם מצפים להודעה]
  ["מסלול נפסל במרחק הליכה — חייבים להסביר", 100, 2000, true],
  ["מסלול סביר — יש זמן, אין מה להסביר", 400, 800, false],
  ["רחוק מכדי ללכת — הממשק כבר אומר זאת, אין להכפיל", 3000, 40000, false],
  ["אין מיקום בכלל — אין מספר ואין הודעה", null, null, false],
  ["המנתב לא ענה — הקו האווירי לגיטימי, יש זמן", 500, null, false],
];

const QUIET = process.argv[2] === "count";
const say = (...a) => { if (!QUIET) console.log(...a); };

let fail = 0;
const check = (ok, label, got, want) => {
  if (!ok) fail++;
  say(`${ok ? "✓" : "✗"} ${label.padEnd(48)} קיבלנו ${got} · צפוי ${want}`);
};

for (const [label, q, places, want] of HOUSE) {
  const got = missingHouseNumber(q, places);
  check(got === want, label, String(got), String(want));
}

for (const [label, air, route, want] of WALK) {
  const got = walkNote(walkEstimate(air, route));
  check(!!got === want, label, got ? "הודעה" : "שתיקה", want ? "הודעה" : "שתיקה");
}

// ── ג. המשפט עצמו, לא רק ההחלטה ─────────────────────────────────
// שתי הפונקציות שמייצרות את הטקסט הן המקור היחיד שלו בכל האתר: שלושה
// מקומות בממשק קוראים להן. בדיקה שבודקת רק "כן/לא" הייתה עוברת גם על
// מחרוזת ריקה, והמשתמש היה רואה אזור שתיקה חדש.
check(
  (houseNumberNote("יוספטל 82 בת ים", [P("יוספטל 92", "92")]) || "").includes("82"),
  "המשפט על מספר הבית נוקב במספר שהוקלד", "כן", "כן");
check(
  houseNumberNote("יוספטל 92 בת ים", [P("יוספטל 92", "92", "יוספטל")]) === null,
  "מספר שנמצא — אין משפט", "כן", "כן");
check(
  (walkNote(walkEstimate(100, 2000)) || "").includes("קו אווירי"),
  "המשפט על ההליכה אומר שהמספר אווירי", "כן", "כן");

// ── ד. בקרה דו-כיוונית: לירות כשצריך, ולשתוק כשצריך ─────────────
// "אפס כשלים" מתוך פונקציה שתמיד מחזירה null נראה בדיוק כמו הצלחה —
// ומאז 10.11 גם ההפך מסוכן: תקלה ב-typedStreet הייתה מדליקה את ההודעה
// על **כל** כתובת, כולל כשהבית נמצא. שני הכיוונים נבדקים כאן.
const canFire =
  missingHouseNumber("רחוב 1", [P("רחוב")]) === "1" &&
  missingHouseNumber("הרמה 1", [P("הרמה 1", "1", "הרמה")]) === null &&
  walkNote({ metres: 100, trustTime: false }) !== null;
check(canFire, "בקרה: יורות כשצריך ושותקות כשצריך", "כן", "כן");

const total = HOUSE.length + WALK.length + 4;
if (QUIET) console.log("%d/%d", fail, total);
else console.log(fail ? `\n${fail} נכשלו` : `\nכל ${total} המקרים עברו`);
process.exit(fail ? 1 : 0);
