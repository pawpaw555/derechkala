# עכשיו נתפסת כל שעה בקוד: במחרוזת, ב-template literal, בטקסט JSX, וגם
# השוואה מספרית של getHours/getMinutes. שורות הערה מנוכות, אחרת ההערה
# שמתעדת את הבאג מפילה את הבדיקה שמונעת אותו, ו-// בתוך כתובת לא נחתך.
# כלל 5ג: סופרים מופעים, לא שורות. התבניות ASCII בלבד, כלל 11.
# המספר השני הוא בקרה חיובית שרצה בכל הרצה, ולא כזו שצריך לזכור: אותה
# פונקציה בדיוק על מתקן עם חמישה מופעים מושתלים בחמש צורות. אם הוא
# יורד מ-5, התבנית נשברה ולא העולם, וכל מספר שלידו חסר משמעות.
hardcoded_hours(){
  grep -vE '^[[:space:]]*(//|\*)' "$1" | sed -E 's|([^:])//.*|\1|' \
  | grep -oE '[0-2][0-9]:[0-5][0-9]|get(Hours|Minutes)\(\) *[<>=!]+ *[0-9]+' \
  | wc -l | tr -d ' '
}
# מדפיס "מופעים · קבצים שנקראו". הקריאה היא דרך read ולא דרך פיצול מילים,
# כי `app/station/[slug]/page.tsx` מכיל סוגריים מרובעים — מחרוזת שעוברת
# פיצול מילים עוברת אחריו גם הרחבת גלוב, ו-`[slug]` היא מחלקת תווים.
# כאן היא לא מתאימה לכלום ולכן נשארת כפשוטה, אבל זה מקרי.
# המספר השני נספר על קבצים שנפתחו בפועל ולא על אורך הרשימה: רשימה שלמה
# שאי אפשר לקרוא הייתה מחזירה 0 מופעים ו-35 "קבצים" ועוברת בשקט.
hh_scan(){
  local n=0 c=0 f
  while IFS= read -r f; do
    [ -z "$f" ] && continue
    [ -r "$f" ] || continue
    n=$(( n + $(hardcoded_hours "$f") ))
    c=$(( c + 1 ))
  done <<< "$1"
  echo "$n · $c"
}
