ok "מחירים מול דנקל החיה" "8/14.5/180 · בקרה: כן" "$(node scripts/fares-live.mjs 2>/dev/null)"
# ושעות השירות, מאותה סיבה ובדחיפות גדולה יותר: דנקל כותבת שהשעות
