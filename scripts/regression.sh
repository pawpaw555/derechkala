gate_counts(){
  local shows=0 gated=0 f
  while IFS= read -r f; do
    [ -z "$f" ] && continue
    case "$f" in */data.ts) continue;; esac
    [ -r "$f" ] || continue
    grep -vE '^[[:space:]]*(//|\*)' "$f" | grep -q 'walkMinutes(' || continue
    shows=$(( shows + 1 ))
    grep -vE '^[[:space:]]*(//|\*)' "$f" | grep -q 'walkEstimate(' && gated=$(( gated + 1 ))
  done <<< "$1"
  echo "$shows · $gated"
}
