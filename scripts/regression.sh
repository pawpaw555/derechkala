#!/usr/bin/env bash
# בלוק הרגרסיה של כלל 6. זהה בכל פעם, לא לפי מקרה.
#
# עד 04.11.2026 `ok` הייתה printf: הבלוק הדפיס 29 מספרים, תמיד הסתיים
# בהצלחה, וההשוואה לציפייה נעשתה בעיניים שלי. כלומר הוא היה דוח ולא
# בדיקה — מספר שהשתנה היה מודפס ועובר, אם לא שמתי לב. עכשיו הציפייה
# היא ארגומנט, ההשוואה בקוד, והסקריפט יוצא בשגיאה על כל ✗.
#
# שלוש שורות שהציפייה בהן אינה מספר קבוע עברו דרך `pos`/`same`, כי
# ציפייה קשיחה בהן הייתה נכשלת לשקר: ספירת ה-`||` בקוד נעה עם כל שינוי,
# ומספר קריאות fitBounds יכול לגדול בלגיטימיות — מה שנדרש שם הוא שהוא
# שווה למספר הדגלים, לא שהוא 3.
set -u
cd "$(dirname "$0")/.."
PORT=${PORT:-3011}
B="http://localhost:$PORT"

PASS=0
FAIL=0
ok(){
  if [ "$3" = "$2" ]; then
    PASS=$((PASS+1)); printf "  ✓ %-44s %s\n" "$1" "$3"
  else
    FAIL=$((FAIL+1)); printf "  ✗ %-44s %s   ← צפוי: %s\n" "$1" "$3" "$2"
  fi
}
# בקרה שהתשובה שלה היא "הכלי רץ", לא מספר: ספירה שנעה עם הקוד אינה
# ציפייה שאפשר לקבע, והשאלה האמיתית היא אם ה-grep מצא משהו בכלל.
pos(){ if [ "$1" -gt 0 ]; then echo "כן"; else echo "לא"; fi; }
# שני מספרים שחייבים להיות שווים זה לזה, ולא שווים לערך מסוים.
same(){ if [ "$1" = "$2" ]; then echo "שווה"; else echo "$1≠$2"; fi; }
# תקרה ולא ערך: כלל 6 מגדיר את lint ואת השדות המתים כ"≤ הבסיס". ציפייה
# מדויקת שם הייתה מדווחת ככשל דווקא על שיפור — 16 בעיות שירדו ל-15 —
# ואז הייתי מתחיל להתעלם מהשורה. ירידה עוברת, עלייה נופלת.
le(){ if [ "$1" -le "$2" ]; then echo "≤$2"; else echo "$1>$2"; fi; }

pkill -f "next start -p $PORT" 2>/dev/null
npm run build > /tmp/reg-build.log 2>&1; BUILD=$?
(npx next start -p "$PORT" > /tmp/reg-srv.log 2>&1 &)

# כלל 5א: ממתינים לעמוד שעליו מודדים, לא רק לשורש
ST="$B/station/%D7%90%D7%91%D7%90%20%D7%94%D7%9C%D7%9C"
for i in $(seq 1 90); do
  [ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 "$ST" 2>/dev/null)" = "200" ] && \
  [ "$(curl -s "$ST" | grep -o '<h2' | wc -l | tr -d ' ')" -gt 0 ] && break
done

S=$(curl -s "$ST")
echo "═══ בלוק רגרסיה ═══"
ok "tsc"  "0" "$(npx tsc --noEmit 2>&1 | grep -c 'error TS')"
ok "build" "0" "$BUILD"
LINTN=$(npm run lint 2>&1 | grep -oE '[0-9]+ problems' | head -1 | grep -oE '[0-9]+')
ok "lint (תקרה)" "≤16" "$(le "${LINTN:-0}" 16)"
# grep -c סופר שורות, ו-Next קובע את מעברי השורה ב-HTML לפי שיקוליו:
# הוספת בלוק <style> אחד הזיזה את אותן מחרוזות מ-2 שורות ל-3 בלי ששום
# תוכן השתנה. סופרים מופעים, ומתוך תשובה אחת ולא שתיים.
HRS=$(curl -s $B/hours)
# 14:10 ו-18:20 מ-08.11.2026, כשהשעות יושרו לדנקל. עד אז 15:40 ו-19:45,
# ושתיהן לא הופיעו בשום שורה אצל המפעילה. הספירות לא זזו — אותם מקומות,
# ערכים אחרים — ולכן הן אינן מעידות על התיקון; מי שמעיד היא השורה
# "שעות מול דנקל החיה".
ok "/hours 14:10 · 18:20" "6 · 8" "$(echo "$HRS"|grep -o '14:10'|wc -l|tr -d ' ') · $(echo "$HRS"|grep -o '18:20'|wc -l|tr -d ' ')"
# המספרים נוספו ב-03.11: עד אז השורה הדפיסה ספירה בלי ציפייה, ולכן לא
# הייתה יכולה להיכשל. ה-10 כולל את "התחנה על המפה" שנוסף אז.
ok "עמוד תחנה h2 · h1" "10 · 1" "$(echo "$S"|grep -o '<h2'|wc -l|tr -d ' ') · $(echo "$S"|grep -o '<h1'|wc -l|tr -d ' ')"
# כלל 10: המפה בעמוד התחנה היא ssr:false, ולכן אין לה סמן ב-HTML. מה
# שכן נשלח מהשרת הוא הכותרת, והיא הסימן שהבלוק קיים בעמוד. המספר השני
# הוא בקרה — כותרת שידוע שקיימת שם מאז ומתמיד.
ok "עמוד תחנה: כותרת המפה · בקרה כתובת" "1 · 1" "$(echo "$S"|grep -o 'התחנה על המפה'|wc -l|tr -d ' ') · $(echo "$S"|grep -o '>כתובת<'|wc -l|tr -d ' ')"
# לחיצה על סמן בוחרת תחנה לשדה. שתי המפות בעמוד התחנה חייבות לקבל את
# הבורר — אחרת אחת מהן תפתח כרטיס ש"תכנן נסיעה לכאן" שבו יוצא לעמוד
# הבית ומאבד את הכיוון שנבחר. המספר השני הוא בקרה: סה״כ המפות בקובץ.
# selectable ב-Map.tsx הוא מה שמונע כרטיס כפול — bindPopup של ליפט פותח
# בלחיצה בעצמו, ולכן הוא מותנה. שלושה מופעים: ההגדרה ושני השימושים.
# כלל 7: סימן פוקוס. תשעה פקדים נושאים outline:"none" ב-style המוטבע,
# והכלל שמחזיר סימן חייב לשבת ב-globals.css ולא בתוך עמוד — כשהוא ישב
# בתוך HomeContent וב-StationClient, ששת ה-select ושדה המאתר ב-/line-red
# וב-/map נשארו בלי שום סימן. השני חייב להיות 0: כלל בעמוד פירושו שהחור
# חזר. השלישי הוא האוכלוסייה שהכלל אמור לכסות — אם הוא עלה, נוסף פקד
# ויש לבדוק שהוא input/select/textarea ולא כפתור או div.
# **והשורה שלמטה בודקת את המקור בלבד.** ייבוא שיוסר מ-layout.tsx משאיר
# את הספירה על 1 ומוחק את הטבעת מכל העמודים. השורה שאחריה שולפת את
# גיליונות הסגנון של העמודים עצמם ומחפשת בהם את ההצהרה — "נשמר"
# ו"מוגש" הם שני דברים שונים, כמו טקסט המחיר שנפלט קטוע ב-154 קבצים.
# **ומה שאף אחת מהשתיים אינה אומרת: שהטבעת נדלקת.** הטריגר הוא :focus
# על מיקוד מקלדת, ובחלונית הדפדפן של הסשן `document.hasFocus()` הוא
# false ו-`querySelectorAll(":focus")` מחזיר 0 גם כששדה הקלט הוא
# activeElement — הסביבה אינה יכולה לענות, וזה נמדד ולא הונח.
# מה שכן נמדד שם ב-08.11: ההצהרה מסוגלת לגבור על ה-style המוטבע, והיא
# זקוקה ל-!important — בלעדיו הגבול נשאר rgb(208,208,220), כי
# `border: 1.5px solid #d0d0dc` יושב inline על השדה.
ok "פוקוס: ב-globals · בעמודים · פקדים" "1 · 0 · 9" "$(grep -c 'select:focus-visible' app/globals.css) · $(grep -rh 'input:focus' app/ --include='*.tsx' | grep -vE '^[[:space:]]*(/\*|\*)' | wc -l | tr -d ' ') · $(grep -rh 'outline: "none"' app/ --include='*.tsx' | wc -l | tr -d ' ')"
# שני הטוגלים הם בחירה אחת מתוך כמה, ולכן radiogroup ולא שורת כפתורים
# לחוצים. השלישי הוא הבקרה ששומרת על זה: aria-pressed אמיתי אחד בלבד
# בכל הקוד, כפתור המצב הכהה, שהוא באמת טוגל דו-מצבי. אם הוא עולה, מישהו
# בנה טוגל חדש ביד במקום להשתמש ברכיב — וגם הניווט בחצים לא יגיע איתו.
ok "טוגלים: radiogroup · קוראים · aria-pressed" "1 · 2 · 1" "$(grep -rh 'role=\"radiogroup\"' app/ --include='*.tsx' | grep -vE '^[[:space:]]*(//|\*|/\*)' | wc -l | tr -d ' ') · $(grep -rh '<RadioPills' app/ --include='*.tsx' | wc -l | tr -d ' ') · $(grep -rh 'aria-pressed' app/ --include='*.tsx' | grep -vE '^[[:space:]]*(//|\*|/\*)' | wc -l | tr -d ' ')"
ok "עמוד תחנה: מפות בוחרות · מפות · selectable" "2 · 2 · 3" "$(grep -c 'onSelectStation={handleSelectStation}' 'app/station/[slug]/StationClient.tsx') · $(grep -c '<Map ' 'app/station/[slug]/StationClient.tsx') · $(grep -c 'selectable' app/lib/Map.tsx)"
ok "TrainStation · FAQPage" "2 · 2" "$(echo "$S"|grep -o 'TrainStation'|wc -l|tr -d ' ') · $(echo "$S"|grep -o 'FAQPage'|wc -l|tr -d ' ')"
ok "/station/<שטות>" "404" "$(curl -s -o /dev/null -w '%{http_code}' $B/station/zzz)"
# כלל 11: הספירות באות מהפרסר היחיד, כדי שהוא יהיה בשימוש ולא ירקב
ok "תחנות·landmarks·pois·places" "34 · 65 · 131 · 22" "$(python3 -I scripts/sources.py counts)"
# כלל 5ב: אותן ארבע ספירות דרך טעינת מודול במקום פירסור טקסט, ועוד הבקרה
# החיובית — חמשת השמות שנושאים גרש חייבים לחזור. פירסור טקסט נשבר עליהם
# ארבע פעמים ביום אחד; שני מסלולים שמסכימים הם מה שתופס את זה בפעם הבאה.
ok "טעינת מודול מול פירסור · גרש" "שווה · 5" "$(same "$(node scripts/load.mjs 2>/dev/null | sed 's/ · גרש.*//')" "$(python3 -I scripts/sources.py counts)") · $(node scripts/load.mjs 2>/dev/null | grep -oE 'גרש: [0-9]+' | grep -oE '[0-9]+')"
# כלל 2: טענה בלי מקור. חמש תקרות שיכולות רק לרדת — אי אפשר להוסיף
# טענה חדשה בלי מקור, וכל אימות שנעשה נועל את עצמו בהורדת התקרה.
# הבקרה קודמת: אם 22 המקומות עם source אינם 22, הטעינה שבורה וחמשת
# המספרים חסרי משמעות.
read -r PLM PPO PSG PAD PNF <<< "$(node scripts/provenance.mjs 2>/dev/null)"
ok "מקורות · בקרה" "22" "$(node scripts/provenance.mjs control 2>/dev/null)"
ok "landmarks בלי קואורדינטה (תקרה)" "≤65" "$(le "${PLM:-999}" 65)"
ok "pois בלי קואורדינטה (תקרה)" "≤131" "$(le "${PPO:-999}" 131)"
ok "places בדירוג single (תקרה)" "≤16" "$(le "${PSG:-999}" 16)"
# התקרה ירדה מ-34 ל-0 ב-05.11.2026: כל 34 הכתובות הושוו לדנקל וקיבלו
# שדה מקור. כלל 6 — אימות מוריד תקרה ונועל את ההישג.
ok "כתובות בלי שדה מקור (תקרה)" "≤0" "$(le "${PAD:-999}" 0)"
# ההשוואה עצמה: הפרשים לא צפויים · הושוו · פערים מוכרעים · שדה מקור · בקרה
ok "כתובות מול דנקל" "0 · 34 · 2 · 0 · בקרה: כן" "$(node scripts/addresses.mjs count 2>/dev/null)"
# והצילום עצמו מול הדף החי, אחרת הוא רשומה שנכתבה פעם. מספר הפאנלים
# הוא הבקרה: פחות מ-34 והחילוץ נשבר, לא הכתובות השתנו.
ok "צילום הכתובות מול הדף החי" "0 · 0 · 34 · פאנלים: 34" "$(node scripts/addresses.mjs live 2>/dev/null)"
# ירדה מ-34 ל-31 ב-07.11.2026: שלוש הטענות החדות ביותר אומתו מול
# ויקיפדיה — ראש העיר השלישי, מייסד מעריב, ו-1936 — וכולן יצאו נכונות.
ok "עובדות שם בלי שדה מקור (תקרה)" "≤31" "$(le "${PNF:-999}" 31)"
# כלל 2: המקורות שהטבלה נשענת עליהם עדיין עונים מה שנרשם. 403 על נת״ע
# ועל govmap אינו תקלה — זה מה שנמדד, והם נקראים רק מדפדפן.
ok "מקורות אימות חיים" "200 200 200 403 403 · בקרה: 1" "$(bash scripts/sources-live.sh)"
# המחיר הוא הטענה היחידה באתר שמי שטועה בה מעלות לקורא כסף. דנקל
# מוגשת מהשרת, ולכן אפשר להשוות את הקביעה שלנו למה שהמפעילה מפרסמת
